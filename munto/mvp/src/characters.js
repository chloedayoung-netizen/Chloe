// 클라이언트가 보낸 상태를 받아 시스템 프롬프트를 만든다.
export function buildSystemPrompt(ch, { bond = 0, memories = [], lastHook = "", ending = false, nickname = "" }) {
  const st = stageFor(bond);
  const mem = memories.slice(-8).map((m) => `- ${m}`).join("\n") || "- (아직 없음)";
  const parts = [
    ch.persona,
    GLOBAL_RULES,
    `[현재 관계 단계: ${st.name}] ${st.note}`,
    nickname ? `[사용자가 정한 호칭: ${nickname}]` : "",
    `[지난 대화에서 기억하는 것]\n${mem}`,
    lastHook ? `[지난번에 남긴 약속/떡밥 — 대화 초반에 자연스럽게 이어 갈 것]\n${lastHook}` : "",
    ending
      ? `[이번 답변은 오늘의 마지막 인사다] 다정하게 마무리하고, ${ch.tomorrowHook} 마지막 줄에 [[내일: 한 줄 요약]] 을 붙인다.`
      : "",
  ];
  return parts.filter(Boolean).join("\n\n");
}

export function publicList() {
  return Object.values(CHARACTERS).map(({ id, name, genre, tagline, opening }) => ({ id, name, genre, tagline, opening }));
}
